import type { Metadata } from "next";

export const SITE_NAME = "ARCANA — The Astral Archive";

/**
 * Public origin used for canonical URLs, the sitemap and social cards.
 * Set NEXT_PUBLIC_SITE_URL for a custom domain; on Vercel the production domain is used automatically.
 */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL ||
  (process.env.VERCEL_PROJECT_PRODUCTION_URL && `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`) ||
  "http://localhost:3000"
).replace(/\/+$/, "");

/** Open Graph fields every page shares; Next replaces (not merges) a parent's openGraph object. */
export const OPEN_GRAPH_DEFAULTS = {
  type: "website" as const,
  siteName: SITE_NAME,
  locale: "en_US",
  alternateLocale: ["vi_VN"],
};

/** Generated by app/opengraph-image.tsx. */
export const SHARE_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: "ARCANA — The Astral Archive: an immersive 3D tarot reading chamber",
};

/** Indexable pages, in sitemap order. */
export const PUBLIC_ROUTES = [
  { path: "/", priority: 1, changeFrequency: "monthly" },
  { path: "/reading", priority: 0.9, changeFrequency: "monthly" },
  { path: "/deck", priority: 0.8, changeFrequency: "monthly" },
  { path: "/legal", priority: 0.3, changeFrequency: "yearly" },
] as const;

/** Title, description, canonical URL and matching Open Graph / Twitter tags for one page. */
export function pageMetadata({
  title,
  description,
  path,
  index = true,
}: {
  title?: string;
  description: string;
  path: string;
  index?: boolean;
}): Metadata {
  const socialTitle = title ? `${title} · ARCANA` : SITE_NAME;
  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    // A page's own openGraph/twitter objects drop the inherited share image, so name it explicitly.
    openGraph: { ...OPEN_GRAPH_DEFAULTS, title: socialTitle, description, url: path, images: [SHARE_IMAGE] },
    twitter: { card: "summary_large_image", title: socialTitle, description, images: [SHARE_IMAGE] },
    ...(index ? {} : { robots: { index: false, follow: true } }),
  };
}
